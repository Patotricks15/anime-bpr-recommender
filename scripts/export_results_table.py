"""Export the evaluation results as a LaTeX table and a Markdown table.

Having one generator feed both `paper/tables/results.tex` and the README block
is what stops the three surfaces from drifting apart as the model changes.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from recommender.cli import _build_models, _load_split  # noqa: E402
from recommender.evaluation import evaluate  # noqa: E402

COLUMNS = ["model", "ndcg", "recall", "mrr", "coverage"]
HEADERS = {
    "model": "Model",
    "ndcg": "NDCG@10",
    "recall": "Recall@10",
    "mrr": "MRR@10",
    "coverage": "Coverage",
}


def compute_results(ratings: Path, k: int, seed: int) -> pd.DataFrame:
    _, split = _load_split(ratings)
    rows = []
    for name, model in _build_models(seed).items():
        model.fit(split)
        rows.append(evaluate(model, split, k=k, partition="test", model_name=name).as_row())
    return pd.DataFrame(rows)[COLUMNS].sort_values("ndcg", ascending=False)


def to_latex(frame: pd.DataFrame, k: int) -> str:
    best = frame["ndcg"].max()
    lines = [
        "% Generated by scripts/export_results_table.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"  \centering",
        rf"  \caption{{Top-$K$ ranking quality on the held-out test partition ($K={k}$).",
        r"  Hyperparameters for every model were selected on the validation",
        r"  partition; the test partition was read once.}",
        r"  \label{tab:results}",
        r"  \begin{tabular}{lrrrr}",
        r"    \toprule",
        "    " + " & ".join(HEADERS[c] for c in COLUMNS) + r" \\",
        r"    \midrule",
    ]
    for _, row in frame.iterrows():
        cells = [str(row["model"]).replace("_", r"\_")]
        for col in COLUMNS[1:]:
            value = f"{row[col]:.4f}"
            cells.append(rf"\textbf{{{value}}}" if col == "ndcg" and row[col] == best else value)
        lines.append("    " + " & ".join(cells) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def to_markdown(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(HEADERS[c] for c in COLUMNS) + " |"
    sep = "|" + "|".join(["---"] * len(COLUMNS)) + "|"
    rows = [
        "| " + " | ".join(
            [str(r["model"])] + [f"{r[c]:.4f}" for c in COLUMNS[1:]]
        ) + " |"
        for _, r in frame.iterrows()
    ]
    return "\n".join([header, sep, *rows])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ratings", type=Path, default=PROJECT_ROOT / "data" / "rating.csv")
    parser.add_argument("--k", type=int, default=10)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    if not args.ratings.exists():
        raise SystemExit(f"{args.ratings} not found. Run scripts/download_data.py --synthetic")

    frame = compute_results(args.ratings, args.k, args.seed)

    tables = PROJECT_ROOT / "paper" / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    (tables / "results.tex").write_text(to_latex(frame, args.k))

    artifacts = PROJECT_ROOT / "artifacts"
    artifacts.mkdir(exist_ok=True)
    frame.to_csv(artifacts / "results.csv", index=False)
    (artifacts / "results.md").write_text(to_markdown(frame) + "\n")

    print(to_markdown(frame))
    print(f"\nwrote {tables / 'results.tex'}")
    print(f"wrote {artifacts / 'results.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
